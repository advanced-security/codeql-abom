package lockfile

import (
	"os"
	"path/filepath"
	"testing"

	native "github.com/github/actions-lockfile/go/pkg/lockfile"
)

// Bytes as `gh actions-lock` writes them. Trimmed to the entries each test needs; the shapes are
// verbatim, because the disagreements between a pin key and its `ref` field are the point.
const (
	coveredLock = `# This file is machine-generated by ` + "`gh actions-lock`" + `.
version: 'v0.0.2'
workflows:
    '.github/workflows/build.yml':
        - 'actions/checkout@v7.0.1'
        - 'actions/cache@55cc8345863c7cc4c66a329aec7e433d2d1c52a9'
    '.github/workflows/empty.yml': []
dependencies:
    'actions/checkout@v7.0.1':
        ref: 'v7.0.1'
        commit: 'sha1-3d3c42e5aac5ba805825da76410c181273ba90b1'
        owner_id: 44036562
        repo_id: 197814629
    'actions/cache@55cc8345863c7cc4c66a329aec7e433d2d1c52a9':
        ref: 'v6.1.0'
        commit: 'sha1-55cc8345863c7cc4c66a329aec7e433d2d1c52a9'
        owner_id: 44036562
        repo_id: 215566462
`

	futureLock = `version: future-version
workflows:
    '.github/workflows/rust-ci.yml':
        - 'missing/action@v1'
dependencies: {}
`
)

// writeLock materializes a repository root holding one lockfile.
func writeLock(t *testing.T, contents string) string {
	t.Helper()
	root := t.TempDir()
	path := filepath.Join(root, native.Path)
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatalf("creating the lockfile directory: %v", err)
	}
	if err := os.WriteFile(path, []byte(contents), 0o600); err != nil {
		t.Fatalf("writing the lockfile: %v", err)
	}
	return root
}

// A repository that has not adopted the feature is a state ABOM records, not a failure. Reporting
// it as an error would push every un-onboarded repository in the corpus down an error path.
func TestARepositoryWithNoLockfileIsNotOnboardedRatherThanAnError(t *testing.T) {
	got, err := Read(t.TempDir())
	if err != nil {
		t.Fatalf("reading a tree with no lockfile: %v", err)
	}
	if got.Coverage != NotOnboarded {
		t.Errorf("coverage = %q, want %q", got.Coverage, NotOnboarded)
	}
	if got.Schema != "" {
		t.Errorf("schema = %q, want empty: there is no lockfile to have one", got.Schema)
	}
}

// The corpus fixture declares `version: future-version`. A schema this consumer cannot read must
// be a named failure and must never degrade into "no lockfile", which would silently hand the
// dependency back to live-tag resolution.
func TestAnUnsupportedSchemaIsNamedRatherThanTreatedAsAbsent(t *testing.T) {
	got, err := Read(writeLock(t, futureLock))
	if err != nil {
		t.Fatalf("reading a future-version lockfile: %v", err)
	}
	if got.Coverage != Unsupported {
		t.Fatalf("coverage = %q, want %q", got.Coverage, Unsupported)
	}
	if got.Reason == "" {
		t.Error("an unsupported lockfile must say why, or nothing downstream can report it")
	}
	// Recorded before normalization, so a later policy change can be told from a changed file.
	if got.Schema != "future-version" {
		t.Errorf("schema = %q, want %q as written", got.Schema, "future-version")
	}
	if got.Digest == "" {
		t.Error("the original bytes must be digested even when they cannot be parsed")
	}
}

// Coverage is per workflow, not per repository: a lockfile can exist and say nothing about a
// given workflow, which is a different fact from the repository having no lockfile at all.
func TestAWorkflowAbsentFromAPresentLockfileIsNotCovered(t *testing.T) {
	got, err := Read(writeLock(t, coveredLock))
	if err != nil {
		t.Fatalf("reading a supported lockfile: %v", err)
	}
	if c := got.Workflow(".github/workflows/build.yml"); c != Covered {
		t.Errorf("listed workflow coverage = %q, want %q", c, Covered)
	}
	if c := got.Workflow(".github/workflows/never-onboarded.yml"); c != NotOnboarded {
		t.Errorf("unlisted workflow coverage = %q, want %q", c, NotOnboarded)
	}
}

// An onboarded workflow with no external dependencies is a recorded empty set. Absent is not zero:
// reporting it as NotOnboarded would lose the fact that somebody did onboard it.
func TestAnOnboardedWorkflowWithNoDependenciesIsEmptyNotAbsent(t *testing.T) {
	got, err := Read(writeLock(t, coveredLock))
	if err != nil {
		t.Fatalf("reading a supported lockfile: %v", err)
	}
	if c := got.Workflow(".github/workflows/empty.yml"); c != Empty {
		t.Errorf("coverage = %q, want %q", c, Empty)
	}
}

// The selection is the digest, never the `ref` field. An entry keyed by commit and narrowed to a
// tag disagrees with itself by design -- `actions/cache@55cc8345...` records `ref: 'v6.1.0'` --
// and upstream's own `ActionsLock.pins` rejects that shape by requiring the two to agree.
func TestSelectionReadsTheDigestEvenWhenTheRefFieldDisagrees(t *testing.T) {
	lock, err := Read(writeLock(t, coveredLock))
	if err != nil {
		t.Fatalf("reading a supported lockfile: %v", err)
	}
	cases := []struct {
		uses string
		want string
	}{
		{"actions/checkout@v7.0.1", "3d3c42e5aac5ba805825da76410c181273ba90b1"},
		{"actions/cache@55cc8345863c7cc4c66a329aec7e433d2d1c52a9", "55cc8345863c7cc4c66a329aec7e433d2d1c52a9"},
		// A repository pin covers its sub-actions; the runner downloads owner/repo@ref once.
		{"actions/cache/save@55cc8345863c7cc4c66a329aec7e433d2d1c52a9", "55cc8345863c7cc4c66a329aec7e433d2d1c52a9"},
	}
	for _, c := range cases {
		got, ok := lock.Selected(".github/workflows/build.yml", c.uses)
		if !ok {
			t.Errorf("%s: no selection, want %s", c.uses, c.want)
			continue
		}
		if got != c.want {
			t.Errorf("%s: selected %s, want %s", c.uses, got, c.want)
		}
	}
}

// References the lockfile format does not describe must not be reported as uncovered, or every
// local and container reference in the corpus becomes a false gap.
func TestReferencesTheFormatDoesNotDescribeAreNotSelections(t *testing.T) {
	lock, err := Read(writeLock(t, coveredLock))
	if err != nil {
		t.Fatalf("reading a supported lockfile: %v", err)
	}
	for _, uses := range []string{
		"./.github/actions/local",
		"$/.github/actions/selfref",
		"docker://alpine:3.20",
		"${{ matrix.action }}",
	} {
		if _, ok := lock.Selected(".github/workflows/build.yml", uses); ok {
			t.Errorf("%s: reported a selection; the lockfile grammar does not cover it", uses)
		}
	}
}

// An unsupported lockfile selects nothing at all. This is the invariant that keeps a broken lock
// from silently becoming today's tag somewhere downstream.
func TestAnUnsupportedLockfileSelectsNothing(t *testing.T) {
	lock, err := Read(writeLock(t, futureLock))
	if err != nil {
		t.Fatalf("reading a future-version lockfile: %v", err)
	}
	if _, ok := lock.Selected(".github/workflows/rust-ci.yml", "missing/action@v1"); ok {
		t.Error("an unsupported lockfile reported a selection")
	}
	if c := lock.Workflow(".github/workflows/rust-ci.yml"); c != Unsupported {
		t.Errorf("workflow coverage = %q, want %q", c, Unsupported)
	}
}
