package closure

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// fixtureTree is the staged closure the query test and the Go fixtures are built from.
const fixtureTree = "../../ql/actions/graph-extraction/test/ResolvedCallees"

// fixtureMembers rebuilds, from the checked-in staged tree, the checkouts the stager would have
// been handed: the owned repository's own files, and each callee's file where it sits in its own
// repository.
func fixtureMembers(t *testing.T) (Root, []Member) {
	t.Helper()
	read := func(rel string) string {
		body, err := os.ReadFile(filepath.Join(fixtureTree, filepath.FromSlash(rel)))
		if err != nil {
			t.Fatalf("reading the fixture: %v", err)
		}
		return string(body)
	}
	root := Root{Repository: "octo/app", Commit: "a1", Tree: tree(t, map[string]string{
		".github/workflows/pr.yml":         read(".github/workflows/pr.yml"),
		".github/actions/local/action.yml": read(".github/actions/local/action.yml"),
	})}
	return root, []Member{
		{Repository: "vendor/comp", Uses: "vendor/comp", Commit: "c1", Tree: tree(t, map[string]string{
			"action.yml": read(".github/actions/external/vendor/comp/action.yml")})},
		{Repository: "vendor/inner", Uses: "vendor/inner", Commit: "i1", Tree: tree(t, map[string]string{
			"action.yml": read(".github/actions/external/vendor/inner/action.yml")})},
		{Repository: "vendor/rw", Uses: "vendor/rw/.github/workflows/reuse.yml", Commit: "r1",
			Tree: tree(t, map[string]string{
				".github/workflows/reuse.yml": read(".github/workflows/external/vendor/rw/.github/workflows/reuse.yml")})},
		// A JavaScript action the root calls: named, never staged.
		{Repository: "actions/checkout", Uses: "actions/checkout", Commit: "j1",
			Tree: tree(t, map[string]string{"action.yml": javascript})},
	}
}

// The fixtures every other package's closure tests read were generated by the CLI from a tree
// checked in by hand. That tree is only evidence about the stager if the stager produces it, so
// this holds the two together byte for byte.
func TestTheStagerReproducesTheCheckedInClosureTree(t *testing.T) {
	root, members := fixtureMembers(t)
	layout, skipped, err := Plan(root, members)
	if err != nil {
		t.Fatalf("Plan: %v", err)
	}
	if len(skipped) != 1 || skipped[0].Repository != "actions/checkout" {
		t.Errorf("skipped %+v, want only the JavaScript action", skipped)
	}
	dst := filepath.Join(t.TempDir(), "src")
	if err := layout.Write(dst); err != nil {
		t.Fatalf("Write: %v", err)
	}

	want := map[string]string{}
	if err := filepath.WalkDir(fixtureTree, func(path string, d os.DirEntry, err error) error {
		if err != nil || d.IsDir() {
			return err
		}
		rel, _ := filepath.Rel(fixtureTree, path)
		// The query test's own files are not part of the staged repository.
		if strings.HasPrefix(filepath.Base(rel), "ResolvedCallees.") {
			return nil
		}
		body, err := os.ReadFile(path)
		want[filepath.ToSlash(rel)] = string(body)
		return err
	}); err != nil {
		t.Fatalf("walking the fixture: %v", err)
	}
	got := map[string]string{}
	if err := filepath.WalkDir(dst, func(path string, d os.DirEntry, err error) error {
		if err != nil || d.IsDir() {
			return err
		}
		rel, _ := filepath.Rel(dst, path)
		body, err := os.ReadFile(path)
		got[filepath.ToSlash(rel)] = string(body)
		return err
	}); err != nil {
		t.Fatalf("walking the staged tree: %v", err)
	}
	for path, body := range want {
		if got[path] != body {
			t.Errorf("%s differs from the fixture, or was not staged", path)
		}
	}
	for path := range got {
		if _, ok := want[path]; !ok {
			t.Errorf("staged %s, which the fixture does not hold", path)
		}
	}
}
