const unsupportedLock = "version: future-version\nworkflows: {}\ndependencies: {}\n"

type queued struct {
	status, resolved, discoveredFrom string
	depth                            int
}

// queuedAt reads one frontier row by its whole key: a dependency at two refs is two rows.
func queuedAt(t *testing.T, h *harness, nodeKey, ref string) (queued, bool) {
	t.Helper()
	var q queued
	err := h.store.DB().QueryRow(`
		SELECT status, COALESCE(resolved_sha, ''), COALESCE(discovered_from, ''), depth
		FROM abom_frontier WHERE node_key = ? AND ref = ?`, nodeKey, ref).
		Scan(&q.status, &q.resolved, &q.discoveredFrom, &q.depth)
	if errors.Is(err, sql.ErrNoRows) {
		return q, false
	}
	if err != nil {
		t.Fatalf("reading %s@%s: %v", nodeKey, ref, err)
	}
	return q, true
}

func refsQueued(t *testing.T, h *harness, nodeKey string) []string {
	t.Helper()
	rows, err := h.store.DB().Query(
		`SELECT ref FROM abom_frontier WHERE node_key = ? ORDER BY ref`, nodeKey)
	if err != nil {
		t.Fatalf("listing refs of %s: %v", nodeKey, err)
	}
	defer rows.Close()
	var refs []string
	for rows.Next() {
		var ref string
		if err := rows.Scan(&ref); err != nil {
			t.Fatalf("scanning a ref of %s: %v", nodeKey, err)
		}
		refs = append(refs, ref)
	}
	if err := rows.Err(); err != nil {
		t.Fatalf("listing refs of %s: %v", nodeKey, err)
	}
	return refs
}

// storeGraph is a lock that names one composite and the one pin it pulls in.
func storeGraph(parentPin, parentCommit, childPin, childCommit string) store.LockGraph {
	parent, _ := pinParts(parentPin)
	child, childRef := pinParts(childPin)
	parentOwner, parentRepo, _ := strings.Cut(parent, "/")
	childOwner, childRepo, _ := strings.Cut(child, "/")
	_, parentRef := pinParts(parentPin)
	return store.LockGraph{
		Dependencies: []store.LockDependency{
			{Pin: parentPin, Owner: parentOwner, Repo: parentRepo, Ref: parentRef,
				Algorithm: "sha1", Digest: parentCommit},
			{Pin: childPin, Owner: childOwner, Repo: childRepo, Ref: childRef,
				Algorithm: "sha1", Digest: childCommit},
		},
		Uses: []store.LockUse{{Parent: parentPin, Child: childPin}},
	}
}

func pinParts(pin string) (nwo, ref string) {
	nwo, ref, _ = strings.Cut(pin, "@")
	return nwo, ref
}

func (h *harness) lockFor(full, lock string) {
	h.mu.Lock()
	defer h.mu.Unlock()
	h.files[full] = map[string]string{".github/workflows/actions.lock": lock}
}

// The commit an onboarded workflow runs is the one its lock names, and that commit is queued as
// its own unit of work. The declared ref stays queued beside it: every reader that describes the
// source as written is keyed on it, and removing it would change what those readers mean.
func TestAnOnboardedWorkflowQueuesTheCommitItsLockSelects(t *testing.T) {
	h := newHarness(t)
	h.lockFor("octo/composite", rootLock)
	h.enqueue(item("octo", "composite", "", 1))

	h.run(10)

	locked, ok := queuedAt(t, h, "actions/setup-node", lockedSetupNode)
	if !ok {
		t.Fatalf("setup-node is queued at %v, want the locked commit among them",
			refsQueued(t, h, "actions/setup-node"))
	}
	if locked.discoveredFrom != "octo/composite" || locked.depth != 2 {
		t.Errorf("locked selection discovered from %q at depth %d, want octo/composite at 2",
			locked.discoveredFrom, locked.depth)
	}
	if _, ok := queuedAt(t, h, "actions/setup-node", "v4"); !ok {
		t.Error("the declared ref is no longer queued; readers keyed on it lose their row")
	}
}

// A lock answers for the workflows it lists and for nothing else. The same pin locked for
// another workflow is that workflow's answer: borrowing it would describe code this one does not
// run, and a SHA the source already names needs no second row.
func TestALockAnswersOnlyForTheWorkflowsItLists(t *testing.T) {
	h := newHarness(t)
	h.lockFor("octo/composite", rootLock)
	h.enqueue(item("octo", "composite", "", 1))

	h.run(10)

	want := []string{pinnedCheckout, "v4"}
	got := refsQueued(t, h, "actions/checkout")
	if len(got) != len(want) || got[0] != want[0] || got[1] != want[1] {
		t.Errorf("actions/checkout is queued at %v, want %v: only what the source declares", got, want)
	}
}

// An unsupported lock is a named coverage failure, and it selects nothing. Declared resolution
// carries on exactly as it would without any lock, which is what "no silent live-tag substitute"
// leaves: the gap is recorded, and nothing claims the dependency is locked.
func TestAnUnsupportedLockSelectsNothing(t *testing.T) {
	h := newHarness(t)
	h.lockFor("octo/composite", unsupportedLock)
	h.enqueue(item("octo", "composite", "", 1))

	h.run(10)

	for _, key := range []string{"actions/setup-node", "actions/checkout", "actions/setup-python"} {
		for _, ref := range refsQueued(t, h, key) {
			if ref == lockedSetupNode || ref == lockedSetupPython {
				t.Errorf("%s queued at %s from a lock nothing could read", key, ref)
			}
		}
	}
	var coverage string
	if err := h.store.DB().QueryRow(`
		SELECT coverage FROM abom_lock_coverage
		WHERE repository = 'octo/composite' AND workflow_path = ''`).Scan(&coverage); err != nil {
		t.Fatalf("reading the recorded coverage: %v", err)
	}
	if coverage != "unsupported" {
		t.Errorf("coverage = %q, want unsupported: the failure has to be on record", coverage)
	}
}

// Which commit a composite action's own `uses:` runs at is decided by its caller's lock, never
// by the composite: the pinned CLI records nested pins in the root lock's DAG and never reads a
// callee's lock. A lock that is no longer what its repository resolves to describes nothing
// anyone runs, so it selects nothing.
func TestACompositeRunsItsNestedPinsAtTheCallersSelection(t *testing.T) {
	h := newHarness(t)
	h.lockFor("octo/composite", rootLock)
	h.enqueue(item("octo", "composite", "", 1))
	h.run(10)

	// A lock the frontier no longer resolves to: a commit of a repository nothing queued.
	if err := h.store.RecordLockReading("octo/retired", "old-commit", lockfile.Reader, nil, storeGraph(
		"octo/tool@v1", lockedToolCommit, "actions/setup-python@v5", historicSetupPython)); err != nil {
		t.Fatalf("recording a lock that is not current: %v", err)
	}

	h.enqueue(item("octo", "tool", "", 2))
	h.drain()

	nested, ok := queuedAt(t, h, "actions/setup-python", lockedSetupPython)
	if !ok {
		t.Fatalf("setup-python is queued at %v, want the caller's locked commit among them",
			refsQueued(t, h, "actions/setup-python"))
	}
	if nested.discoveredFrom != "octo/tool" {
		t.Errorf("discovered from %q, want the composite that names it", nested.discoveredFrom)
	}
	if _, ok := queuedAt(t, h, "actions/setup-python", historicSetupPython); ok {
		t.Error("a lock no frontier row resolves to selected a commit")
	}
	if _, ok := queuedAt(t, h, "actions/setup-python", "v5"); !ok {
		t.Error("the declared ref is no longer queued")
	}
}

// A locked selection is a commit, so a tag moving upstream cannot move it: it is analyzed at the
// commit the lock names and never drift-probed. The declared ref beside it still follows the tag.
func TestALockedSelectionIsAnalyzedAtItsCommitAndNeverRechecked(t *testing.T) {
	h := newHarness(t)
	h.lockFor("octo/composite", rootLock)
	h.enqueue(item("octo", "composite", "", 1))
	h.run(10)
	h.probe.moveEverythingTo("sha-moved")
	h.run(100)

	locked, ok := queuedAt(t, h, "actions/setup-node", lockedSetupNode)
	if !ok || locked.status != frontier.StatusDone {
		t.Fatalf("locked selection = %+v (queued %v), want done", locked, ok)
	}
	if locked.resolved != lockedSetupNode {
		t.Errorf("analyzed at %s, want the locked commit %s", locked.resolved, lockedSetupNode)
	}
	declared, _ := queuedAt(t, h, "actions/setup-node", "v4")
	if declared.resolved != "sha-moved" {
		t.Errorf("declared ref analyzed at %s, want where the tag points now", declared.resolved)
	}

	due, err := h.queue.DueForRecheck(-time.Hour, 1000)
	if err != nil {
		t.Fatalf("DueForRecheck: %v", err)
	}
	for _, d := range due {
		if d.NodeKey == "actions/setup-node" && d.Requested == lockedSetupNode {
			t.Error("a locked commit is due for a drift probe; a commit cannot move")
		}
	}
}

// Invented, like the tool it stands beside.
const localSetupPython = "0f0f0f0f0f0f0f0f0f0f0f0f0f0f0f0f0f0f0f0f"

// ownLock locks the pin the recorded edges reach only through the repository's own composite,
// `./.github/actions/greet`, under the workflow named here. The pinned CLI lists a local
// composite's pins under each workflow that calls it; there is no DAG entry for a local action.
func ownLock(workflow string) string {
	return lockHeader + `workflows:
    '` + workflow + `':
        - 'actions/setup-python@v5'
dependencies:
    'actions/setup-python@v5':
        ref: 'v5'
        commit: 'sha1-` + localSetupPython + `'
        owner_id: 44036562
        repo_id: 162064890
`
}

// A step inside the consumer's own composite runs in whichever workflow calls it, and that
// workflow's lock is what selects its commit. `main.yml` calls `greet`, whose step names
// `actions/setup-python@v5`.
func TestAConsumersOwnCompositeRunsAtTheLockOfTheWorkflowThatCallsIt(t *testing.T) {
	h := newHarness(t)
	h.lockFor("octo/composite", ownLock(".github/workflows/main.yml"))
	h.enqueue(item("octo", "composite", "", 1))

	h.run(10)

	got, ok := queuedAt(t, h, "actions/setup-python", localSetupPython)
	if !ok {
		t.Fatalf("setup-python is queued at %v, want the calling workflow's locked commit",
			refsQueued(t, h, "actions/setup-python"))
	}
	if got.discoveredFrom != "octo/composite" {
		t.Errorf("discovered from %q, want the consumer", got.discoveredFrom)
	}
}

// A workflow that does not call the composite has no say in it, even with the same pin locked.
// `reusable.yml` never reaches `greet`.
func TestAConsumersOwnCompositeDoesNotBorrowTheLockOfAWorkflowThatDoesNotCallIt(t *testing.T) {
	h := newHarness(t)
	h.lockFor("octo/composite", ownLock(".github/workflows/reusable.yml"))
	h.enqueue(item("octo", "composite", "", 1))

	h.run(10)

	if _, ok := queuedAt(t, h, "actions/setup-python", localSetupPython); ok {
		t.Error("the composite took a selection from a workflow that never calls it")
	}
}

// A lock another reader read is read again, and reading it is all that happens: the tree is
// fetched, the lock recorded by the current reader, and every evaluation answered from the ledger.
func TestALockAnotherReaderReadIsReadAgainWithoutAnalyzingAnything(t *testing.T) {
	h := newHarness(t)
	h.lockFor("octo/composite", rootLock)
	h.enqueue(item("octo", "composite", "", 1))
	h.drain()
	if _, err := h.store.DB().Exec(
		`UPDATE abom_lock_coverage SET reader = 'an older parser' WHERE repository = 'octo/composite'`); err != nil {
		t.Fatalf("recording the reading as another reader's: %v", err)
	}

	n, err := h.store.RequeueLocksReadByAnotherReader(lockfile.Reader)
	if err != nil {
		t.Fatalf("RequeueLocksReadByAnotherReader: %v", err)
	}
	if n != 1 {
		t.Fatalf("requeued %d, want the one repository whose lock another reader read", n)
	}
	fetched, built := len(h.fetched), len(h.built)
	h.run(100)

	if again := h.fetched[fetched:]; len(again) != 1 || again[0] != "octo/composite" {
		t.Errorf("fetched %v again, want octo/composite alone", again)
	}
	if len(h.built) != built {
		t.Errorf("built %d databases, want none: nothing about the commit changed", len(h.built)-built)
	}
	var reader string
	if err := h.store.DB().QueryRow(`
		SELECT reader FROM abom_lock_coverage
		WHERE repository = 'octo/composite' AND workflow_path = ''`).Scan(&reader); err != nil {
		t.Fatalf("reading the recorded reader: %v", err)
	}
	if reader != lockfile.Reader {
		t.Errorf("recorded by %q, want %q", reader, lockfile.Reader)
	}
}
