// SPDX writes the document as SPDX 2.3.
//
// 2.3 rather than 3.0: `spdx/tools-golang` supports 2.1 through 2.3 and nothing later, and 3.0 is
// JSON-LD that would be hand-rolled with no reference implementation to check against.
//
// The format has no field for "we did not look at this", so coverage goes into the document
// comment and each package's own comment. Dropping it because the format has no slot would let an
// unexamined component read as a clean one.
func SPDX(doc store.BOM) ([]byte, error) {
	name := documentName(doc.Roots)
	out := &spdx.Document{
		SPDXVersion:    spdx.Version,
		DataLicense:    spdx.DataLicense,
		SPDXIdentifier: "DOCUMENT",
		DocumentName:   name,
		// Deterministic rather than a UUID: a reader regenerates the document and compares, and
		// a fresh namespace every run would make every comparison fail.
		DocumentNamespace: "https://github.com/advanced-security/codeql-abom/" + name,
		DocumentComment:   coverageStatement(doc),
		CreationInfo: &spdx.CreationInfo{
			Created:  doc.GeneratedAt,
			Creators: []common.Creator{{CreatorType: "Tool", Creator: "codeql-abom"}},
		},
	}

	ids := newIDs()
	byKey := map[string]common.ElementID{}
	for _, c := range doc.Components {
		id := common.ElementID(ids.of(c.Key))
		byKey[c.Key] = id
		out.Packages = append(out.Packages, &spdx.Package{
			PackageName:             c.Key,
			PackageSPDXIdentifier:   id,
			PackageVersion:          cycloneVersion(c),
			PackageDownloadLocation: downloadLocation(c),
			// Nothing here reads a license, so claiming one either way would be a fabricated
			// fact. NOASSERTION is the format's word for "not examined".
			PackageLicenseConcluded: "NOASSERTION",
			PackageLicenseDeclared:  "NOASSERTION",
			PackageCopyrightText:    "NOASSERTION",
			FilesAnalyzed:           false,
			PackageComment:          componentStatement(c),
		})
	}

	// A document whose packages are unreachable from it states no scope at all.
	for _, c := range doc.Components {
		if !c.Direct {
			continue
		}
		out.Relationships = append(out.Relationships, &spdx.Relationship{
			RefA:         common.MakeDocElementID("", "DOCUMENT"),
			RefB:         common.MakeDocElementID("", string(byKey[c.Key])),
			Relationship: "DESCRIBES",
		})
	}
	for _, r := range doc.Relationships {
		a, okA := byKey[r.Source]
		b, okB := byKey[r.Target]
		if !okA || !okB {
			continue
		}
		out.Relationships = append(out.Relationships, &spdx.Relationship{
			RefA:         common.MakeDocElementID("", string(a)),
			RefB:         common.MakeDocElementID("", string(b)),
			Relationship: "DEPENDS_ON",
			// The boundary has no SPDX equivalent, so it rides in the comment rather than
			// being lost.
			RelationshipComment: relationshipComment(r),
		})
	}

	var buf bytes.Buffer
	if err := spdxjson.Write(out, &buf, spdxjson.Indent("  ")); err != nil {
		return nil, fmt.Errorf("encoding SPDX: %w", err)
	}
	return buf.Bytes(), nil
}

func coverageStatement(doc store.BOM) string {
	cov := doc.Coverage
	return fmt.Sprintf(
		"Generated by codeql-abom from %s. "+
			"Components referenced: %d, of which analyzed: %d. "+
			"References in use: %d, of which analyzed: %d. "+
			"Findings: %d, of which not traceable to a recorded query run: %d, "+
			"without a result hash: %d, without a pack digest: %d. "+
			"A component that was not analyzed is included and marked; absence of a finding "+
			"against it is not evidence that none exists.",
		strings.Join(doc.Roots, ", "),
		cov.ComponentsInUse, cov.ComponentsAnalyzed,
		cov.ReferencesInUse, cov.ReferencesAnalyzed,
		cov.Findings, cov.FindingsUntraced, cov.FindingsWithoutHash, cov.FindingsWithoutDigest)
}

func componentStatement(c store.BOMComponent) string {
	state := "not analyzed"
	if c.Analyzed {
		state = "analyzed"
	}
	relation := "indirect"
	if c.Direct {
		relation = "direct"
	}
	refs := make([]string, 0, len(c.References))
	for _, r := range c.References {
		if r.Raw == "" {
			continue
		}
		// What runs for the repositories this document is about, beside what they wrote.
		for _, l := range r.Locked {
			refs = append(refs, r.Raw+" locked=> "+l.Commit+" ("+strings.Join(l.Consumers, ", ")+")")
		}
		if r.ResolvedSHA != "" {
			refs = append(refs, r.Raw+" => "+r.ResolvedSHA)
			continue
		}
		refs = append(refs, r.Raw)
	}
	out := fmt.Sprintf("%s; %s dependency at depth %d; references analyzed %d of %d",
		state, relation, c.Depth, c.RefsAnalyzed, c.RefsInUse)
	if len(refs) > 0 {
		out += "; referenced as " + strings.Join(refs, ", ")
	}
	for _, a := range c.Advisories {
		// Reported beside the references, never applied to them.
		out += fmt.Sprintf("; advisory %s (%s) published against range %s, not evaluated "+
			"against the references above", a.GHSAID, a.Severity, a.VulnerableRange)
	}
	return out
}

func relationshipComment(r store.BOMRelationship) string {
	if r.Boundary == "" {
		return r.Kind + "; boundary unknown"
	}
	return r.Kind + "; " + r.Boundary
}

func downloadLocation(c store.BOMComponent) string {
	if c.Repository == "" {
		return "NOASSERTION"
	}
	return "git+https://github.com/" + c.Repository + ".git"
}

var notSPDXSafe = regexp.MustCompile(`[^a-zA-Z0-9.-]+`)

// ids hands out SPDX element ids that are unique within one document.
//
// The character set SPDX allows is narrower than a node key's, so distinct components can reduce
// to one id: `actions/upload-artifact/merge` and `actions/upload-artifact-merge` did exactly that
// on the reference corpus. Two packages sharing an id makes the document invalid, and silently
// merging two dependencies into one is worse than that.
type ids struct{ taken map[string]int }

func newIDs() *ids { return &ids{taken: map[string]int{}} }

func (i *ids) of(key string) string {
	base := strings.Trim(notSPDXSafe.ReplaceAllString(key, "-"), "-")
	if base == "" {
		// A key made entirely of punctuation, such as the unevaluated `${{ }}` expression that
		// reaches the graph verbatim.
		base = "unnamed"
	}
	id := "SPDXRef-" + base
	if n, clash := i.taken[id]; clash {
		i.taken[id] = n + 1
		// Suffixed rather than hashed, so the readable name survives and a reader can still see
		// which component it is.
		return fmt.Sprintf("%s-%d", id, n+1)
	}
	i.taken[id] = 1
	return id
}

// documentName names the document after what it is about, without pasting every root into one
// unreadable string: 44 roots produced a 1,400-character name.
func documentName(roots []string) string {
	switch len(roots) {
	case 0:
		return "abom-document"
	case 1:
		return "abom-" + strings.Trim(notSPDXSafe.ReplaceAllString(roots[0], "-"), "-")
	default:
		owner := roots[0]
		if i := strings.Index(owner, "/"); i > 0 {
			owner = owner[:i]
		}
		return fmt.Sprintf("abom-%s-and-%d-more",
			strings.Trim(notSPDXSafe.ReplaceAllString(owner, "-"), "-"), len(roots)-1)
	}
}
