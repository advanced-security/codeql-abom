// PostgreSQL keeps API flags as integers and timestamps as RFC3339 text, including NULL.
// These functions adapt only the small SQLite expression vocabulary used by the shared queries.
const postgresFunctions = `
CREATE COLLATION IF NOT EXISTS abom_nocase (provider = icu, locale = 'und-u-ks-level2', deterministic = false);
CREATE OR REPLACE FUNCTION abom_integer(value bigint) RETURNS bigint
LANGUAGE sql IMMUTABLE STRICT AS $$ SELECT value $$;
CREATE OR REPLACE FUNCTION abom_integer(value boolean) RETURNS bigint
LANGUAGE sql IMMUTABLE STRICT AS $$ SELECT CASE WHEN value THEN 1::bigint ELSE 0::bigint END $$;
CREATE OR REPLACE FUNCTION abom_integer(value text) RETURNS bigint
LANGUAGE sql IMMUTABLE STRICT AS $$ SELECT value::bigint $$;
CREATE OR REPLACE FUNCTION abom_integer(value numeric) RETURNS bigint
LANGUAGE sql IMMUTABLE STRICT AS $$ SELECT trunc(value)::bigint $$;
CREATE OR REPLACE FUNCTION abom_integer(value double precision) RETURNS bigint
LANGUAGE sql IMMUTABLE STRICT AS $$ SELECT trunc(value)::bigint $$;
CREATE OR REPLACE FUNCTION abom_json_valid(value text) RETURNS boolean LANGUAGE plpgsql IMMUTABLE AS $$
BEGIN
  IF value IS NULL THEN RETURN false; END IF;
  PERFORM value::jsonb; RETURN true;
EXCEPTION WHEN invalid_text_representation THEN RETURN false;
END $$;
CREATE OR REPLACE FUNCTION abom_json_extract(value text, path text) RETURNS text
LANGUAGE sql IMMUTABLE STRICT AS $$
WITH selected AS (SELECT value::jsonb #> string_to_array(substr(path, 3), '.') AS v)
SELECT CASE WHEN v = 'true'::jsonb THEN '1' WHEN v = 'false'::jsonb THEN '0' ELSE v #>> '{}' END FROM selected
$$;
CREATE OR REPLACE FUNCTION abom_json_each(input text, path text DEFAULT '$')
RETURNS TABLE(key text, value text, type text) LANGUAGE sql IMMUTABLE STRICT AS $$
WITH document AS (
  SELECT CASE WHEN path = '$' THEN input::jsonb
         ELSE input::jsonb #> string_to_array(substr(path, 3), '.') END AS doc
), members AS (
  SELECT (a.ordinality-1)::text AS key, a.value
    FROM document, jsonb_array_elements(CASE WHEN jsonb_typeof(doc) = 'array' THEN doc ELSE '[]'::jsonb END)
         WITH ORDINALITY AS a
  UNION ALL
  SELECT o.key, o.value FROM document,
       jsonb_each(CASE WHEN jsonb_typeof(doc) = 'object' THEN doc ELSE '{}'::jsonb END) AS o
)
SELECT key, CASE WHEN value = 'true'::jsonb THEN '1' WHEN value = 'false'::jsonb THEN '0'
                 WHEN jsonb_typeof(value) = 'null' THEN NULL ELSE value #>> '{}' END,
       CASE jsonb_typeof(value) WHEN 'string' THEN 'text' ELSE jsonb_typeof(value) END
FROM members
$$;
CREATE OR REPLACE FUNCTION abom_julianday(value text) RETURNS double precision LANGUAGE plpgsql STABLE STRICT AS $$
BEGIN
  RETURN extract(epoch FROM value::timestamptz)::double precision / 86400.0 + 2440587.5;
EXCEPTION WHEN invalid_datetime_format OR datetime_field_overflow THEN RETURN NULL;
END $$;
CREATE OR REPLACE FUNCTION abom_substr2(value text, start bigint)
RETURNS text LANGUAGE sql IMMUTABLE STRICT AS $$
SELECT substr(value, greatest(CASE WHEN start < 0 THEN length(value)+start+1 ELSE start END,1)::integer)
$$;
CREATE OR REPLACE FUNCTION abom_substr3(value text, start bigint, count bigint)
RETURNS text LANGUAGE sql IMMUTABLE STRICT AS $$
WITH location AS (SELECT CASE WHEN start < 0 THEN length(value)+start+1 ELSE start END AS pos)
SELECT CASE WHEN count >= 0 THEN
  substr(value, greatest(pos,1)::integer, greatest(count+least(pos-1,0),0)::integer)
ELSE substr(value, greatest(pos+count,1)::integer, greatest(-count+least(pos+count-1,0),0)::integer)
END FROM location
$$;
CREATE TABLE IF NOT EXISTS abom_store_revision (
  singleton integer PRIMARY KEY CHECK (singleton = 1),
  revision bigint NOT NULL
);
INSERT INTO abom_store_revision VALUES (1, 0) ON CONFLICT DO NOTHING;
CREATE OR REPLACE FUNCTION abom_bump_revision() RETURNS trigger LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
BEGIN
  UPDATE abom_store_revision SET revision = revision + 1 WHERE singleton = 1;
  RETURN NULL;
END $$;
`

// Native table declarations share column definitions, not SQLite migration/rebuild machinery.
func postgresTableDDL(ddl string) (string, error) {
	t, err := lexSQL(ddl)
	if err != nil {
		return "", err
	}
	var out []sqlToken
	for i := 0; i < len(t); i++ {
		v := t[i]
		switch {
		case tokenIs(v, "TEXT"):
			if !columnHasCollation(t[i+1:]) {
				v.text = `TEXT COLLATE "C"`
			}
		case tokenIs(v, "INTEGER"):
			v.text = "BIGINT"
			if i+2 < len(t) && tokenIs(t[i+1], "PRIMARY") && tokenIs(t[i+2], "KEY") {
				v.text = "BIGINT GENERATED BY DEFAULT AS IDENTITY"
			}
		case tokenIs(v, "AUTOINCREMENT"):
			continue
		case tokenIs(v, "WITHOUT") && i+1 < len(t) && tokenIs(t[i+1], "ROWID"):
			i++
			continue
		case tokenIs(v, "REAL"):
			v.text = "DOUBLE PRECISION"
		case tokenIs(v, "BLOB"):
			v.text = "BYTEA"
		}
		out = append(out, v)
	}
	return postgresSQL(renderSQL(out))
}

func columnHasCollation(t []sqlToken) bool {
	depth := 0
	for _, token := range t {
		if depth == 0 && (token.text == "," || token.text == ")" || token.text == ";") {
			return false
		}
		if tokenIs(token, "COLLATE") {
			return true
		}
		switch token.text {
		case "(":
			depth++
		case ")":
			depth--
		}
	}
	return false
}

func (s *Store) migratePostgres() error {
	tx, err := s.db.DB.Begin()
	if err != nil {
		return err
	}
	defer tx.Rollback()
	if _, err := tx.Exec(publicationLockSQL); err != nil {
		return fmt.Errorf("locking PostgreSQL migration: %w", err)
	}
	if _, err := tx.Exec(postgresFunctions); err != nil {
		return fmt.Errorf("creating PostgreSQL functions: %w", err)
	}
	if err := createPostgresTables(tx); err != nil {
		return err
	}
	if err := tx.Commit(); err != nil {
		return err
	}
	if err := s.finishMigration(); err != nil {
		return err
	}
	return s.trackPostgresWrites()
}

func createPostgresTables(tx *sql.Tx) error {
	tables := append([]struct{ what, ddl string }{{"base tables", schemaDDL}}, createTables...)
	for _, table := range tables {
		q, err := postgresTableDDL(table.ddl)
		if err != nil {
			return err
		}
		if _, err := tx.Exec(q); err != nil {
			return fmt.Errorf("creating PostgreSQL %s: %w", table.what, err)
		}
	}
	for _, c := range addedColumns {
		q, err := postgresTableDDL(fmt.Sprintf("ALTER TABLE %s ADD COLUMN IF NOT EXISTS %s %s", c.table, c.column, c.decl))
		if err != nil {
			return err
		}
		if _, err := tx.Exec(q); err != nil {
			return fmt.Errorf("adding PostgreSQL %s.%s: %w", c.table, c.column, err)
		}
	}
	for _, table := range []string{"abom_check_part", "abom_workflow_run", "abom_lock_coverage",
		"abom_lock_dependency", "abom_lock_use", "abom_lock_workflow_pin"} {
		if _, err := tx.Exec(`ALTER TABLE ` + table + ` ADD COLUMN IF NOT EXISTS rowid BIGINT GENERATED ALWAYS AS IDENTITY`); err != nil {
			return fmt.Errorf("adding recorded order to %s: %w", table, err)
		}
	}
	return nil
}

func (s *Store) trackPostgresWrites() error {
	// A transaction changes the revision atomically with its writes, including non-graph facts.
	rows, err := s.db.DB.Query(`SELECT tablename FROM pg_tables WHERE schemaname = current_schema()
		AND (tablename = 'repository' OR starts_with(tablename, 'abom_'))
		AND tablename NOT IN ('abom_store_revision', 'abom_coordination_lease', 'abom_ingest_receipt')`)
	if err != nil {
		return err
	}
	var tablesWithTriggers []string
	for rows.Next() {
		var name string
		if err := rows.Scan(&name); err != nil {
			_ = rows.Close()
			return err
		}
		tablesWithTriggers = append(tablesWithTriggers, name)
	}
	if err := rows.Err(); err != nil {
		_ = rows.Close()
		return err
	}
	if err := rows.Close(); err != nil {
		return err
	}
	for _, table := range tablesWithTriggers {
		name := pq.QuoteIdentifier(table)
		if _, err := s.db.DB.Exec(`CREATE OR REPLACE TRIGGER abom_revision
			BEFORE INSERT OR UPDATE OR DELETE OR TRUNCATE ON ` + name + `
			FOR EACH STATEMENT EXECUTE FUNCTION abom_bump_revision()`); err != nil {
			return fmt.Errorf("tracking PostgreSQL writes to %s: %w", table, err)
		}
	}
	for _, table := range []string{"abom_coordination_lease", "abom_ingest_receipt"} {
		if _, err := s.db.DB.Exec(`DROP TRIGGER IF EXISTS abom_revision ON ` + table); err != nil {
			return fmt.Errorf("separating coordination from graph cache tracking: %w", err)
		}
	}
	return nil
}
